def check_celocli_exists() -> bool:
    """Check if the celocli binary exists in PATH using only stdlib."""
    paths = os.environ.get("PATH", "").split(os.pathsep)
    exts = [""] + (
        os.environ.get("PATHEXT", "").split(os.pathsep) if os.name == "nt" else []
    )
    for path in paths:
        for ext in exts:
            full_path = os.path.join(path, "celocli" + ext)
            if os.path.isfile(full_path) and os.access(full_path, os.X_OK):
                return True
    return False


def fetch_celo_cli_csv(network: str, command: str) -> str:
    """Run celocli and return its CSV output."""
    try:
        result = subprocess.run(
            [
                "celocli",
                command,
                "--node",
                NETWORKS[network]["l2_rpc"],
                "--csv",
            ],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            check=True,
        )
        return result.stdout.strip()
    except subprocess.CalledProcessError as e:
        sys.exit(f"Error: celocli failed:\n{e.stderr}")
    except FileNotFoundError:
        sys.exit("Error: celocli binary not found in PATH.")


def csv_to_markdown(csv_text: str, network: str) -> str:
    """Convert CSV text to Markdown table with proxy links."""
    reader = csv.DictReader(io.StringIO(csv_text))
    lines = ["| Contract | Proxy |", "| -------- | ------ |"]
    for row in reader:
        contract = row.get("Contract", "").strip()
        proxy = row.get("Proxy", "").strip()
        if proxy:
            link = f"[`{proxy}`]({NETWORKS[network]['l2_explorer']}/address/{proxy})"
            lines.append(f"| {contract} | {link} |")
    return "\n".join(lines)


def token_csv_to_markdown(csv_text: str, network: str) -> str:
    reader = csv.DictReader(io.StringIO(csv_text))
    sorted_rows = sorted(reader, key=lambda row: row["Symbol"].lower())
    lines = [
        "| Token | Symbol | feeCurrency Address | Token Address |",
        "| ----- | ------ | ------------------- | ------------- |",
    ]
    for row in sorted_rows:
        contract = row.get("Name", "").strip()
        symbol = row.get("Symbol", "").strip()
        address = row.get("Token Address", "").strip()
        # The allowlisted address is what you pass as `feeCurrency`. For tokens that do
        # not use 18 decimals it is an adapter, not the token itself.
        fee_currency = row.get("Whitelisted Address", "").strip()
        if address:
            lines.append(
                f"| {contract} | {symbol} "
                f"| {explorer_link(fee_currency, network)} "
                f"| {explorer_link(address, network)} |"
            )
    return "\n".join(lines)


def explorer_link(address: str, network: str) -> str:
    """Render an address as a Markdown link to that network's L2 explorer."""
    if not address:
        return "-"
    return f"[`{address}`]({NETWORKS[network]['l2_explorer']}/address/{address})"


def load_stablecoin_data() -> dict:
    """Load curated stablecoin metadata that has no on-chain registry to read from."""
    with Path("scripts/data/stablecoins.json").open() as f:
        return json.load(f)


def stablecoins_to_markdown(csv_by_network: dict, data: dict) -> str:
    """Build one stablecoin table spanning both networks.

    Mento tokens plus USDC/USDT come from the fee-currency allowlist, which is the only
    source that covers Celo Sepolia. Third-party issuers have no registry to read, so
    they are curated in scripts/data/stablecoins.json.
    """
    issuers = data["issuers"]
    overrides = {
        k: v for k, v in data["sepolia_overrides"].items() if not k.startswith("_")
    }

    def allowlisted_stablecoins(csv_text: str) -> dict:
        """Map symbol -> token address, keeping only stablecoins."""
        found = {}
        for row in csv.DictReader(io.StringIO(csv_text)):
            symbol = row.get("Symbol", "").strip()
            name = row.get("Name", "").strip()
            address = row.get("Token Address", "").strip()
            is_stablecoin = name.startswith("Mento ") or symbol in FIAT_BACKED_SYMBOLS
            if address and is_stablecoin:
                if symbol in found and found[symbol] != address:
                    print(
                        f"  ! {symbol} is allowlisted more than once; "
                        f"pin the current deployment in scripts/data/stablecoins.json"
                    )
                found[symbol] = address
        return found

    mainnet = allowlisted_stablecoins(csv_by_network["mainnet"])
    sepolia = allowlisted_stablecoins(csv_by_network["celo-sepolia"])
    sepolia.update(overrides)

    lines = [
        "| Stablecoin | Issuer | Celo Mainnet | Celo Sepolia Testnet |",
        "| ---------- | ------ | ------------ | -------------------- |",
    ]

    for symbol in sorted(mainnet, key=str.lower):
        issuer = issuers.get(symbol, issuers["_default"])
        lines.append(
            f"| **{symbol}** | [{issuer['name']}]({issuer['url']}) "
            f"| {explorer_link(mainnet[symbol], 'mainnet')} "
            f"| {explorer_link(sepolia.get(symbol, ''), 'celo-sepolia')} |"
        )

    for token in sorted(data["third_party"], key=lambda t: t["symbol"].lower()):
        # Once a curated token is allowlisted as a fee currency it is already rendered
        # above, with testnet coverage the curated entry cannot provide.
        if token["symbol"] in mainnet:
            continue
        lines.append(
            f"| **{token['symbol']}** | [{token['issuer']}]({token['issuer_url']}) "
            f"| {explorer_link(token['mainnet_address'], 'mainnet')} "
            f"| {explorer_link(token.get('sepolia_address', ''), 'celo-sepolia')} |"
        )

    return "\n".join(lines)


def get_l1_contracts(network: str) -> str:
    net = NETWORKS[network]
    base_url = net["l1_explorer"]

    lines = ["| Contract | Address |", "| -------- | ------- |"]
    with tempfile.TemporaryDirectory() as tmpdir:
        tmppath = Path(tmpdir)
        for filename, url in net["files"].items():
            urlretrieve(url, tmppath / filename)

        l1 = json.load(open(tmppath / "contracts-l1.json"))

        for contract, address in l1.items():
            if address == ZERO_ADDRESS:
                continue

            print("L1:", contract)
            lines.append(f"| {contract} | [`{address}`]({base_url}/address/{address}) |")

            if contract.endswith("Proxy"):
                impl = retrieve_impl(contract, address, net)
                if impl is None:
                    print("  No implementation found!")
                    continue

                print("  Impl:", impl)
                lines.append(f"| {contract.replace('Proxy', 'Impl')} | [`{impl}`]({base_url}/address/{impl}) |")

    return "\n".join(lines)

def bytes32_to_address(b: str) -> str:
    if len(b) != 66 or not b.startswith("0x"):
        raise ValueError(f"Invalid bytes32: {b}")
    return f"0x{b[26:]}"

def resolve_delegate_proxy(contract, address, net) -> Optional[str]:
    # compute storage slot for address manager
    manager_slot = subprocess.check_output(
        [
            "cast",
            "index",
            "address",
            address,
            "1",
        ],
        encoding="utf-8",
    ).strip()

    # load address manager address from storage
    manager_address = subprocess.check_output(
        [
            "cast",
            "storage",
            "-r",
            net["l1_rpc"],
            address,
            manager_slot,
        ],
        encoding="utf-8",
    ).strip()

    # if no address manager, return
    if manager_address == ZERO_BYTES32:
        return None

    manager_address = bytes32_to_address(manager_address)

    # retrieve implementation address from address manager
    impl = subprocess.check_output(
        [
            "cast",
            "call",
            "-r",
            net["l1_rpc"],
            manager_address,
            "getAddress(string)(address)",
            f'OVM_{contract.replace("Proxy", "")}',
        ],
        encoding="utf-8",
    ).strip()

    return impl

def retrieve_impl(contract, address, net) -> tuple[bool, str]:
    impl = subprocess.check_output(
        [
            "cast",
            "storage",
            "-r",
            net["l1_rpc"],
            address,
            PROXY_SLOT,
        ],
        encoding="utf-8",
    ).strip()

    if impl == ZERO_BYTES32:
        return resolve_delegate_proxy(contract, address, net)

    impl = bytes32_to_address(impl)

    return impl

def main():
    if not check_celocli_exists():
        sys.exit(
            "Error: 'celocli' binary not found. Please install it first: npm install -g @celo/celocli"
        )

    print("Fetching core contract data from celocli...")
    with Path("tooling/contracts/core-contracts.mdx").open("w") as f:
        f.write(PAGE_HEADER_CORE_CONTRACTS)

        for network, data in NETWORKS.items():
            print(f"> Fetching contract data from celocli for {network}...")

            csv_output = fetch_celo_cli_csv(network, "network:contracts")
            markdown = csv_to_markdown(csv_output, network)

            f.write(f"\n\n## {data['display_name']}\n\n")
            f.write(markdown)

    print("Fetching fee currency data from celocli...")
    whitelist_csv = {}
    with Path("tooling/contracts/token-contracts.mdx").open("w") as f:
        f.write(PAGE_HEADER_TOKEN_CONTRACTS)

        for network, data in NETWORKS.items():
            print(
                f"> Fetching fee currency contract data from celocli for {network}..."
            )

            csv_output = fetch_celo_cli_csv(network, "network:whitelist")
            whitelist_csv[network] = csv_output
            markdown = token_csv_to_markdown(csv_output, network)

            f.write(f"\n\n## {data['display_name']}\n\n")
            f.write(markdown)

    print("Building stablecoin contract page...")
    with Path("tooling/contracts/stablecoin-contracts.mdx").open("w") as f:
        f.write(PAGE_HEADER_STABLECOIN_CONTRACTS)
        f.write("\n\n")
        f.write(stablecoins_to_markdown(whitelist_csv, load_stablecoin_data()))

    print("Fetching L1 contract data...")
    with Path("tooling/contracts/l1-contracts.mdx").open("w") as f:
        f.write(PAGE_HEADER_L1_CONTRACTS)

        for network, data in NETWORKS.items():
            print(
                f"> Fetching l1 contract data for {network}..."
            )

            markdown = get_l1_contracts(network)

            f.write(f"\n\n## {data['display_name']}\n\n")
            f.write(markdown)


if __name__ == "__main__":
    main()
